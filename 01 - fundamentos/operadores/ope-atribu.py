# SÃO OPERADORES UTILIZADOS PARA DEFINIR O VALOR INICIAL OU SOBRESCREVER O VALOR DE UMA VARIAVEL

# ATRIBUIÇÃO SIMPLES
saldo = 500
print(saldo)

# ATRIBUIÇÃO COM ADIÇÃO 

saldo = 500
saldo += 200 #pego um valor que ja está dentro da variavel e apenas adiciono mais outro valor

print(saldo) 

# ATRIBUIÇÃO COM SUBTRAÇÃO

saldo = 400
saldo -= 100

print(saldo)

# ATRIBUIÇÃO COM MULTIPLICAÇÃO 
saldo = 100
saldo *= 4

print(saldo)

# ATRIBUIÇÃO COM DIVISÃO
saldo = 5000
saldo /= 5

print(saldo)

saldo = 5000
saldo //= 5

print(saldo)

# ATRIBUIÇÃO COM MODULOS
saldo = 430
saldo %= 3

print(saldo)

# ATRIBUIÇÃO COM EXPONENCIAÇÃO
saldo = 40
saldo **= 4

print(saldo)

