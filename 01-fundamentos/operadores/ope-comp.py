# COMPARADORES - SEMPRE O OUTPUT VEM EM BOOLEANO [TRUE OR FALSE]

# IGUALDADE 

saldo = 400
saque = 200

print(saldo == saque)

# DIFERENCA

saldo = 400
saque = 200

print(saldo != saque)

# MAIOR QUE / MAIOR OU IGUAL

saldo = 400
saque = 200

print(saldo > saque)
print(saldo >= saque)

# MENOR QUE / MENOR OU IGUAL

saldo = 400
saque = 200

print(saldo < saque)
print(saldo <= saque)
